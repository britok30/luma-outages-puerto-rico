// Builds lib/pr-paths.ts — simplified, pre-projected SVG paths for the
// lightweight region map — from lib/puerto-rico.json.
// Run after changing the GeoJSON: node scripts/build-map-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";

const geo = JSON.parse(readFileSync(new URL("../lib/puerto-rico.json", import.meta.url)));
const WIDTH = 1000;
const TOLERANCE = 0.0015; // degrees (~150 m)
const MIN_AREA = 0.00002; // drop specks smaller than ~0.2 km²
// Mona and Desecheo sit far west; leaving them out (as the Mapbox view does)
// lets the main island fill the frame.
const WEST_LIMIT = -67.35;

const polygonsOf = (f) =>
  (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates).filter((poly) =>
    poly[0].some(([lon]) => lon >= WEST_LIMIT)
  );
const rings = geo.features.flatMap((f) => polygonsOf(f).flat());
const lons = rings.flat().map((p) => p[0]);
const lats = rings.flat().map((p) => p[1]);
const [minLon, maxLon, minLat, maxLat] = [Math.min(...lons), Math.max(...lons), Math.min(...lats), Math.max(...lats)];
const kx = Math.cos((((minLat + maxLat) / 2) * Math.PI) / 180);
const scale = WIDTH / ((maxLon - minLon) * kx);
const height = Math.ceil((maxLat - minLat) * scale);
const project = ([lon, lat]) => [(lon - minLon) * kx * scale, (maxLat - lat) * scale];

const sqSegDist = (p, a, b) => {
  let [x, y] = a;
  let dx = b[0] - x, dy = b[1] - y;
  if (dx || dy) {
    const t = Math.max(0, Math.min(1, ((p[0] - x) * dx + (p[1] - y) * dy) / (dx * dx + dy * dy)));
    x += dx * t; y += dy * t;
  }
  dx = p[0] - x; dy = p[1] - y;
  return dx * dx + dy * dy;
};
const simplify = (pts, tol) => {
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = sqSegDist(pts[i], pts[a], pts[b]);
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol * tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
};
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0)) / 2;
const fmt = (n) => Math.round(n * 10) / 10;

const regions = geo.features.map((f) => {
  const polys = polygonsOf(f);
  let d = "";
  let largest = null;
  for (const poly of polys) {
    for (const [ri, ring] of poly.entries()) {
      if (area(ring) < MIN_AREA) continue;
      const pts = simplify(ring, TOLERANCE).map(project);
      if (pts.length < 4) continue;
      d += "M" + pts.map((p) => `${fmt(p[0])} ${fmt(p[1])}`).join("L") + "Z";
      if (ri === 0 && (!largest || area(ring) > largest.a)) largest = { a: area(ring), pts };
    }
  }
  // Label anchor: area-weighted centroid of the largest outer ring.
  let cx = 0, cy = 0, a2 = 0;
  const r = largest.pts;
  for (let i = 0; i < r.length; i++) {
    const [x0, y0] = r[i], [x1, y1] = r[(i + 1) % r.length];
    const c = x0 * y1 - x1 * y0;
    a2 += c; cx += (x0 + x1) * c; cy += (y0 + y1) * c;
  }
  return { name: f.properties.name, d, label: [fmt(cx / (3 * a2)), fmt(cy / (3 * a2))] };
});

const out = `// Generated by scripts/build-map-paths.mjs from lib/puerto-rico.json. Do not edit.
export const PR_VIEWBOX = { width: ${WIDTH}, height: ${height} } as const;

export const PR_REGION_PATHS: ReadonlyArray<{ name: string; d: string; label: readonly [number, number] }> = ${JSON.stringify(regions, null, 2)};
`;
writeFileSync(new URL("../lib/pr-paths.ts", import.meta.url), out);
console.log(`lib/pr-paths.ts: ${(out.length / 1024).toFixed(1)} KB, viewBox ${WIDTH}x${height}`, regions.map((r) => `${r.name}@${r.label}`).join(" "));
